"""Generate the API reference from the code, so it cannot drift.

A hand-written signature list is wrong the first time somebody adds a keyword
argument. This reads each module's real signatures and docstrings and writes
`docs/api/reference.md`; `--check` fails when the file on disk differs, so the
document is a fact about the code rather than a memory of it.

    python -m refactory_dsh.tools.gen_api_reference          # write
    python -m refactory_dsh.tools.gen_api_reference --check  # verify

Symbols are attributed to the module that **defines** them, not to every module
that re-exports them: `refactory_dsh.nn` re-exports its whole surface, and a
reference that listed `Knob` under six modules would be six times as long and no
more informative. The package root is listed once, as the public entry point.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import sys
import types
from pathlib import Path
from typing import Any, Union, get_args, get_origin

#: Modules a reader may import from, in the order the reference presents them.
MODULES: tuple[str, ...] = (
    "refactory_dsh.nn",
    "refactory_dsh.nn.graph",
    "refactory_dsh.nn.knob",
    "refactory_dsh.nn.mode",
    "refactory_dsh.nn.declarations",
    "refactory_dsh.nn.edits",
    "refactory_dsh.nn.validate",
    "refactory_dsh.optim",
    "refactory_dsh.optim.compose",
    "refactory_dsh.optim.policies",
    "refactory_dsh.outerloop",
    "refactory_dsh.evaluators",
    "refactory_dsh.adopt",
    "refactory_dsh.steering",
    "refactory_dsh.strategies",
    "refactory_dsh.loop",
    "refactory_dsh.history",
    "refactory_dsh.ir",
    "refactory_dsh.lowering",
    "refactory_dsh.registry",
    "refactory_dsh.toolchain",
    "refactory_dsh.sandbox",
    "refactory_dsh.create",
    "refactory_dsh.edit",
    "refactory_dsh.design",
    "refactory_dsh.repo_change",
    "refactory_dsh.observe",
    "refactory_dsh.cli",
    "refactory_dsh.console",
    "refactory_dsh.discovery",
    "refactory_dsh.worker_config",
    "refactory_dsh.workers",
    "refactory_dsh.profiles",
    "refactory_dsh.items",
)

#: Names a reader imports from the package root, which the root module defines by
#: re-export. Listed with the module that owns the definition.
ROOT_RE_EXPORTS = ("Mode", "Graph", "Node", "Edge", "Knob", "Package", "Port", "Memory", "Invariant")

# <repo>/refactory/refactory_dsh/tools/gen_api_reference.py -> <repo>/refactory/docs/api/
OUT = Path(__file__).resolve().parents[2] / "docs" / "api" / "reference.md"

HEADER = """\
<!-- Generated by refactory_dsh.tools.gen_api_reference. Do not edit by hand:
     run `python -m refactory_dsh.tools.gen_api_reference` after changing the code. -->

# API reference

Every public module, with the real signature and the first line of its docstring.
Generated from the code by `python -m refactory_dsh.tools.gen_api_reference`, and
checked by `refactory/tests/test_docs_api.py` — so a signature here is a fact about
the code, not a copy of it.

Prose for a module's *purpose* lives in the [architecture overview](../architecture.md);
this page is the index.
"""

class _AnnotationText:
    """Render an evaluated annotation without turning it into a quoted string."""

    def __init__(self, text: str) -> None:
        self.text = text

    def __repr__(self) -> str:
        return self.text


def _stable_annotation(annotation: Any) -> Any:
    """Keep evaluated union signatures stable across Python's typing repr change."""
    if get_origin(annotation) not in (Union, types.UnionType):
        return annotation
    return _AnnotationText(" | ".join(
        "None" if arg is type(None) else inspect.formatannotation(_stable_annotation(arg))
        for arg in get_args(annotation)
    ))


#: A signature's rendered form, or empty when the object takes no arguments.
def _signature(obj: Any) -> str:
    try:
        signature = inspect.signature(obj)
        return str(signature.replace(
            parameters=[parameter.replace(annotation=_stable_annotation(parameter.annotation))
                        for parameter in signature.parameters.values()],
            return_annotation=_stable_annotation(signature.return_annotation),
        ))
    except (TypeError, ValueError):
        return ""


def _summary(obj: Any) -> str:
    """The first non-empty line of the docstring, one line."""
    doc = inspect.getdoc(obj) or ""
    for line in doc.splitlines():
        if line.strip():
            return line.strip()
    return ""


def _kind(obj: Any) -> str:
    if inspect.isclass(obj):
        return "class"
    if inspect.isroutine(obj):
        return "function"
    return "constant"


def _entries(module_name: str) -> list[tuple[str, str, str, str]]:
    """The public symbols ``module_name`` defines, as (kind, name, signature, summary)."""
    module = importlib.import_module(module_name)
    declared = getattr(module, "__all__", None)
    names = sorted(declared) if declared else sorted(n for n in vars(module) if not n.startswith("_"))
    entries: list[tuple[str, str, str, str]] = []
    for name in names:
        obj = getattr(module, name, None)
        if obj is None or inspect.ismodule(obj):
            continue
        owner = getattr(obj, "__module__", "")
        # Keep a symbol only where it is defined, plus the package root's
        # deliberate re-exports, so the reference lists each thing once.
        if owner != module_name and not (module_name == "refactory_dsh.nn" and name in ROOT_RE_EXPORTS):
            continue
        entries.append((_kind(obj), name, _signature(obj), _summary(obj)))
    return entries


def render() -> str:
    """The whole reference, as markdown."""
    lines = [HEADER]
    for module_name in MODULES:
        module = importlib.import_module(module_name)
        entries = _entries(module_name)
        if not entries:
            continue
        module_doc = (inspect.getdoc(module) or "").splitlines()
        lines.append(f"\n<a id=\"{module_name.replace('.', '-')}\"></a>\n")
        lines.append(f"## `{module_name}`\n")
        if module_doc:
            lines.append(f"{module_doc[0].strip()}\n")
        lines.append("| kind | name | signature |")
        lines.append("|---|---|---|")
        for kind, name, signature, _summary in entries:
            rendered = signature.replace("|", "\\|") if signature else ""
            lines.append(f"| {kind} | `{name}` | `{rendered}` |")
        lines.append("")
        for kind, name, _signature_text, summary in entries:
            if not summary:
                continue
            lines.append(f"- **`{name}`** — {summary}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m refactory_dsh.tools.gen_api_reference",
        description="Generate or verify docs/api/reference.md from the code.",
    )
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    args = parser.parse_args(argv)

    rendered = render()
    if args.check:
        if not OUT.exists():
            print(f"gen-api-reference: {OUT} does not exist", file=sys.stderr)
            return 1
        if OUT.read_text() != rendered:
            print(
                f"gen-api-reference: {OUT} is stale; run "
                "`python -m refactory_dsh.tools.gen_api_reference`",
                file=sys.stderr,
            )
            return 1
        print("gen-api-reference: docs/api/reference.md is current.")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered)
    print(f"gen-api-reference: wrote {OUT}")
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main()
    raise SystemExit(main())
